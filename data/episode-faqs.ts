export function getEpisodeFaq(slug: string): EpisodeFaq | undefined {
  return EPISODE_FAQS[slug];
}

export function listEpisodeFaqSlugs(): string[] {
  return Object.keys(EPISODE_FAQS);
}

export type EpisodeFaqCoverage = {
  total: number;
  covered: number;
  ratio: number;
  missingSlugs: string[];
};

/**
 * 對照傳入的全部 slug 清單，計算已寫 episode FAQ 的覆蓋率。
 * 呼叫端請傳入 `getStories().map((s) => s.slug)`（本檔不依賴 data/content.ts，
 * 避免與 enrichStory() 合併時產生循環匯入）。
 */
export function episodeFaqCoverage(allSlugs: string[]): EpisodeFaqCoverage {
  const missingSlugs = allSlugs.filter((slug) => !(slug in EPISODE_FAQS));
  const covered = allSlugs.length - missingSlugs.length;
  return {
    total: allSlugs.length,
    covered,
    ratio: allSlugs.length > 0 ? covered / allSlugs.length : 0,
    missingSlugs,
  };
}
